import {test,expect} from "@playwright/test";
test("device research keeps a favorite across locales, saves comparison and clears records",async({page})=>{
 await page.goto("/tr/tractors/",{waitUntil:"domcontentloaded"});
 const cards=page.locator(".tractor-card");
 test.skip((await cards.count())<2,"Offline build lacks two published models.");
 const first=cards.first(),model=await first.locator("[data-price-for]").getAttribute("data-price-for");
 const detail=await first.locator(".tractor-card-main").getAttribute("href");
 await page.goto(detail,{waitUntil:"domcontentloaded"});
 const favorite=page.locator("[data-research-favorite]");
 await expect(favorite).toBeVisible();
 await favorite.click();await expect(favorite).toHaveAttribute("aria-pressed","true");
 await page.reload({waitUntil:"domcontentloaded"});
 await expect(favorite).toHaveAttribute("aria-pressed","true");
 await page.goto("/tractors/#research-workspace",{waitUntil:"domcontentloaded"});
 await expect(page.locator('[data-research-list="favorites"] li a').first()).toBeVisible();
 await page.locator('[data-research-list="favorites"] li a').nth(1).click();
 await expect(page.locator("#tc-left")).toHaveValue(model);
 await page.locator("#tc-shared").click();
 const save=page.locator("[data-research-save]");
 await expect(save).toBeEnabled();
 await save.click();
 await expect(page.locator('[data-research-list="comparisons"] li a')).toHaveCount(1);
 const href=await page.locator('[data-research-list="comparisons"] li a').getAttribute("href");
 expect(new URL(href,page.url()).searchParams.get("view")).toBe("shared");
 await page.goto("/ja/tractors/#research-workspace",{waitUntil:"domcontentloaded"});
 await expect(page.locator('[data-research-list="comparisons"] li a')).toHaveCount(1);
 expect(await page.locator('[data-research-list="comparisons"] li a').getAttribute("href")).toMatch(/^\/ja\/compare\//);
 await page.locator("[data-research-clear-recent]").click();
 await expect(page.locator('[data-research-list="recent"] li a')).toHaveCount(0);
 page.once("dialog",dialog=>dialog.accept());await page.locator("[data-research-clear]").click();
 await expect(page.locator('[data-research-list="favorites"] li a')).toHaveCount(0);
 await expect(page.locator('[data-research-list="comparisons"] li a')).toHaveCount(0);
});
