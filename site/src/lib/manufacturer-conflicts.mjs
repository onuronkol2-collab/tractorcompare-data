const TIGRE_ITALIAN="https://www.antoniocarraro.it/it/catalogo/tigre-3800-f";
const TIGRE_ENGLISH="https://www.antoniocarraro.it/en/catalogue/tigre-3800-f";
const MACH="https://www.antoniocarraro.it/en/catalogue/mach-2-r";
const SONALIKA="https://www.sonalika.com/tractor/gt-22-4wd";

function actualSpecs(model) {
 return Array.isArray(model?.specifications)?model.specifications:[];
}
function sameModel(model,brand,name) {
 return model?.brand_name===brand&&model?.model_name===name;
}

/**
 * Exact model identity is the source-dispute gate, not the availability of
 * disputed rows in the PUBLIC catalogue. Supabase's approved public view
 * already filters these uncertain engine-volume claims. The user-facing
 * warning must survive that safety filter and cite BOTH reviewed OEM pages.
 * A newly verified model variant can later be separated explicitly.
 */
export function hasUnresolvedTigreDisplacement(model) {
 return sameModel(model,"Antonio Carraro","TIGRE 3800 F") &&
   (!model.variant || /stage\s*v/i.test(String(model.variant)));
}

export function modelSourceDiscrepancies(model,lang="en") {
 const copy=OEM_SOURCE_CONFLICT_COPY[lang]||OEM_SOURCE_CONFLICT_COPY.en;
 if(hasUnresolvedTigreDisplacement(model))
   return [{id:"tigre-displacement",message:copy.tigre,
     sourceUrls:[TIGRE_ITALIAN,TIGRE_ENGLISH]}];
 if(sameModel(model,"Antonio Carraro","MACH 2 R") &&
    actualSpecs(model).some(s=>s.source_url===MACH &&
      /74[.,]2/.test(String(s.spec_value)) && /hp/i.test(String(s.unit||""))))
   return [{id:"mach-power",message:copy.mach,sourceUrls:[MACH]}];
 if(sameModel(model,"Sonalika","GT 22 4WD") &&
    actualSpecs(model).some(s=>s.source_url===SONALIKA))
   return [{id:"sonalika-drive",message:copy.sonalika,sourceUrls:[SONALIKA]}];
 return [];
}

/**
 * Raw source-specific claims remain available in model details with clear
 * provenance, but contradictory engine volumes cannot become side-by-side
 * comparable measurements or AI short-answer claims.
 */
export function isUnresolvedComparisonSpec(model,spec) {
 return hasUnresolvedTigreDisplacement(model) &&
  ["engine_displacement_cc","engine_displacement","engine_displacement_l",
   "engine_description"].includes(spec?.canonical_key||"");
}
